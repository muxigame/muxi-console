def preview():
    """Original orthographic contact sheet, useful before native Minecraft QA."""
    width, height = 960, 520
    pixels = canvas(width, height, "F2EFE5")
    depth = [-math.inf] * (width * height)
    mesh = models()
    tiles = ["block/desk_console", "block/screen", "block/cartridge_writer",
             "item/template_handheld", "item/template_cartridge", "item/controller"]
    # Top and north faces visible, like a camera above the front-right corner.
    def project(x, y, z, cx, cy):
        return (cx + (x - 8) * 10 + (z - 8) * 5,
                cy - (y - 7) * 10 - (z - 8) * 3 - (x - 8) * 1.5,
                y - z + x * 0.5)

    def triangle(vertices, color):
        a, b, c = vertices
        low_x, high_x = max(0, int(min(v[0] for v in vertices))), min(width - 1, math.ceil(max(v[0] for v in vertices)))
        low_y, high_y = max(0, int(min(v[1] for v in vertices))), min(height - 1, math.ceil(max(v[1] for v in vertices)))
        divisor = (b[1] - c[1]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[1] - c[1])
        if not divisor:
            return
        for y in range(low_y, high_y + 1):
            for x in range(low_x, high_x + 1):
                u = ((b[1] - c[1]) * (x - c[0]) + (c[0] - b[0]) * (y - c[1])) / divisor
                v = ((c[1] - a[1]) * (x - c[0]) + (a[0] - c[0]) * (y - c[1])) / divisor
                w = 1 - u - v
                if min(u, v, w) >= -1e-5:
                    d = u * a[2] + v * b[2] + w * c[2]
                    index = y * width + x
                    if d > depth[index]:
                        depth[index] = d
                        pixels[index] = color
    for index, name in enumerate(tiles):
        cx, cy = 160 + index % 3 * 320, 130 + index // 3 * 260
        rect(pixels, width, cx - 140, cy - 110, cx + 140, cy + 110, "E6E4D9")
        text_pixels(pixels, width, cx - 130, cy - 98, f"{index + 1:02d}", COLORS["ink"], 2)
        for element in mesh[name]["elements"]:
            x0, y0, z0 = element["from"]
            x1, y1, z1 = element["to"]
            face_vertices = {
                "up": [(x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)],
                "north": [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0)],
                "east": [(x1, y0, z0), (x1, y0, z1), (x1, y1, z1), (x1, y1, z0)],
            }
            for face, vertices in face_vertices.items():
                material = element["faces"][face]["texture"][1:]
                color = COLORS.get(material, COLORS["amber"] if material == "accent" else
                                   COLORS["shell"] if material == "label" else COLORS["screen"])
                shade = {"up": 1.1, "north": 0.95, "east": 0.72}[face]
                rgb = tuple(min(255, int(v * shade)) for v in rgba(color)[:3]) + (255,)
                pts = [project(*vertex, cx, cy) for vertex in vertices]
                triangle(pts[:3], rgb)
                triangle([pts[0], pts[2], pts[3]], rgb)
    out = ROOT / "build/assets-preview.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(png(width, height, pixels))
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="read-only deterministic and closure checks")
    parser.add_argument("--preview", action="store_true", help="write an original model contact sheet under build/")
    args = parser.parse_args()
    files = generated_files()
    checks = check_closure(files)
    mismatches = []
    for relative, payload in files.items():
        path = RESOURCES / relative
        if args.check:
            if not path.is_file() or path.read_bytes() != payload:
                mismatches.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(payload)
    for relative, old_payload in legacy_palette_files().items():
        path = RESOURCES / relative
        if path.exists():
            if args.check:
                mismatches.append(relative + " (obsolete non-atlas path)")
            elif not path.resolve().is_relative_to(RESOURCES.resolve()) or path.read_bytes() != old_payload:
                raise ValueError(f"Refusing to remove changed or external legacy palette: {path}")
            else:
                path.unlink()
    if mismatches:
        raise SystemExit("Generated resource drift:\n" + "\n".join(mismatches))
    print(f"{'Verified' if args.check else 'Generated'} {len(files)} original resources; {checks} closure checks; {len(PLATFORMS)} platform variants.")
    if args.preview:
        print(f"Software illustration (not Minecraft acceptance): {preview()}")


if __name__ == "__main__":
    main()
