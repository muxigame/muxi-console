def check_closure(files):
    """Resolve inherited model textures and all local references, not just JSON syntax."""
    checks = 0

    def require(path):
        nonlocal checks
        checks += 1
        if path not in files:
            raise ValueError(f"Missing resource: {path}")

    def local_model(resource):
        namespace, path = resource.split(":", 1)
        if namespace != NS:
            raise ValueError(f"Unexpected model namespace: {resource}")
        return f"{ASSETS}/models/{path}.json"

    def resolved(path, stack=()):
        require(path)
        if path in stack:
            raise ValueError(f"Cyclic model inheritance: {path}")
        model = json.loads(files[path])
        if "parent" in model:
            inherited = resolved(local_model(model["parent"]), (*stack, path))
            inherited["textures"].update(model.get("textures", {}))
            if "elements" in model:
                inherited["elements"] = model["elements"]
            return inherited
        return copy.deepcopy(model)

    for path, payload in files.items():
        if path.endswith(".json"):
            data = json.loads(payload)
            checks += 1
            if "/models/" in path:
                full = resolved(path)
                textures = full["textures"]
                for texture in textures.values():
                    if texture.startswith("#"):
                        continue
                    namespace, texture_path = texture.split(":", 1)
                    if namespace != NS:
                        raise ValueError(f"Unexpected texture namespace: {texture}")
                    # MC 1.21.1's vanilla blocks atlas has directory sources for
                    # block/ and item/. Existing files outside those sources are
                    # not implicitly stitched just because a model names them.
                    if not texture_path.startswith(("block/", "item/")):
                        raise ValueError(f"Model texture is outside block/item atlas sources: {texture}")
                    require(f"{ASSETS}/textures/{texture_path}.png")
                    checks += 1
                for element in full["elements"]:
                    if not all(0 <= a < b <= 16 for a, b in zip(element["from"], element["to"])):
                        raise ValueError(f"Invalid model element bounds: {path}")
                    for face in element["faces"].values():
                        key = face["texture"]
                        visited = set()
                        while key.startswith("#"):
                            if key in visited or key[1:] not in textures:
                                raise ValueError(f"Unresolved texture {key}: {path}")
                            visited.add(key)
                            key = textures[key[1:]]
                        checks += 1
                for override in data.get("overrides", []):
                    require(local_model(override["model"]))
            if "/blockstates/" in path:
                for variant in data["variants"].values():
                    require(local_model(variant["model"]))
            if "/recipe/" in path:
                output = data["result"]["id"].split(":", 1)[1]
                if output not in ITEMS or output == "cartridge":
                    raise ValueError(f"Invalid crafting output: {output}")
                require(f"{ASSETS}/models/item/{output}.json")
        if path.endswith(".png"):
            checks += 1
            try:
                decode_png(payload)
            except ValueError as error:
                raise ValueError(f"Invalid decoded PNG {path}: {error}") from error
    for name in ITEMS:
        require(f"{ASSETS}/models/item/{name}.json")
    locales = [json.loads(files[f"{ASSETS}/lang/{locale}.json"]) for locale in ("zh_cn", "en_us")]
    if set(locales[0]) != set(locales[1]):
        raise ValueError("Locale key sets differ")
    for platform, *_ in PLATFORMS:
        if f"platform.{NS}.{platform}" not in locales[0]:
            raise ValueError(f"Missing platform translation: {platform}")
        checks += 1
    # A palette edit cannot satisfy the platform-shape requirement. Compare only
    # geometry coordinates so textures, labels and colors have no influence.
    shape_signatures = {}
    media_signatures = {}
    for cmd,(platform,*_) in enumerate(PLATFORMS,1):
        model_path = f"{ASSETS}/models/block/desk_console_{platform}.json"
        full = resolved(model_path)
        coords = [(e["from"],e["to"]) for e in full["elements"]]
        signature = hashlib.sha256(json.dumps(coords,separators=(",",":")).encode()).hexdigest()
        if signature in shape_signatures:
            raise ValueError(f"Platforms share geometry: {platform}, {shape_signatures[signature]}")
        shape_signatures[signature] = platform
        media = resolved(f"{ASSETS}/models/item/cartridge_{platform}.json")
        signature = json.dumps([(e["from"],e["to"]) for e in media["elements"]])
        if signature in media_signatures:
            raise ValueError(f"Platforms share media geometry: {platform}, {media_signatures[signature]}")
        media_signatures[signature] = platform
        for item in ("desk_console","handheld","cartridge"):
            override = json.loads(files[f"{ASSETS}/models/item/{item}.json"])["overrides"][cmd-1]
            if override != {"predicate":{"custom_model_data":cmd},"model":f"{NS}:item/{item}_{platform}"}:
                raise ValueError(f"Unstable CMD mapping: {platform}/{item}")
            checks += 1
        if platform in HANDHELD_PLANES:
            x0,y0,x1,y1,z = HANDHELD_PLANES[platform]
            expected = {"gb":10/9,"gbc":10/9,"gba":3/2,"gg":10/9,"lynx":80/51,
                        "ngp":20/19,"ngpc":20/19,"ws":14/9,"wsc":14/9}[platform]
            if not math.isclose((x1-x0)/(y1-y0),expected,rel_tol=1e-8):
                raise ValueError(f"Handheld display aspect mismatch: {platform}")
            checks += 1
    double = resolved(f"{ASSETS}/models/block/arcade_cabinet_2p.json")
    single = resolved(f"{ASSETS}/models/block/desk_console_arcade.json")
    if [(e["from"],e["to"]) for e in single["elements"]] == [(e["from"],e["to"]) for e in double["elements"]]:
        raise ValueError("Single- and two-seat arcade cabinets must differ in shape")
    checks += 1
    # Assemble the authored six tiles in north-facing world coordinates. The
    # entire active rectangle must have exact area and unbroken texture UVs;
    # per-block front borders would create six small screens instead of one.
    screen_states = json.loads(files[f"{ASSETS}/blockstates/screen.json"])["variants"]
    expected_active_area = 46.5 * 31
    area = 0
    for index in range(6):
        column, row = index % 3, index // 3
        model = resolved(f"{ASSETS}/models/block/screen_{index}.json")
        active = [element for element in model["elements"] if element["faces"]["north"]["texture"] == "#display"]
        if len(active) != 1:
            raise ValueError("A screen tile must expose one continuous active portion")
        element = active[0]
        x0, y0, _ = element["from"]
        x1, y1, _ = element["to"]
        world_x0, world_x1 = x0 - 16 * column, x1 - 16 * column
        world_y0, world_y1 = y0 + 16 * row, y1 + 16 * row
        expected = [max(-31.25, -16 * column), max(.5, 16 * row),
                    min(15.25, 16 - 16 * column), min(31.5, 16 + 16 * row)]
        if [world_x0, world_y0, world_x1, world_y1] != expected:
            raise ValueError("Screen tiles leave a gap or overrun the large active plane")
        area += (x1 - x0) * (y1 - y0)
        uv = element["faces"]["north"]["uv"]
        if not math.isclose((uv[2] - uv[0]) * (uv[3] - uv[1]),
                            (x1 - x0) * (y1 - y0) / expected_active_area * 256, rel_tol=1e-12):
            raise ValueError("Screen standby texture sections do not partition the full image")
        for direction, angle in (("north", 0), ("east", 90), ("south", 180), ("west", 270)):
            if screen_states[f"facing={direction},part={index+1}"] != {
                    "model":f"{NS}:block/screen_{index}","y":angle}:
                raise ValueError("Large-screen state and authored tile mapping differ")
            checks += 1
        checks += 3
    if not math.isclose(area, expected_active_area, rel_tol=1e-12):
        raise ValueError("Six-part screen does not fill the full 3:2 active plane")
    for direction, angle in (("north", 0), ("east", 90), ("south", 180), ("west", 270)):
        if screen_states[f"facing={direction},part=0"] != {"model":f"{NS}:block/screen","y":angle}:
            raise ValueError("Existing one-block screens must retain the legacy model")
        checks += 1
    dock = resolved(f"{ASSETS}/models/block/handheld_dock.json")
    if max(element["to"][1] for element in dock["elements"]) > 3:
        raise ValueError("Dock rises above the low cradle height")
    dock_geometry = [(element["from"],element["to"]) for element in dock["elements"]]
    if dock_geometry == [(e["from"],e["to"]) for e in resolved(f"{ASSETS}/models/block/desk_console.json")["elements"]]:
        raise ValueError("Handheld dock must have its own low geometry")
    checks += 3
    # Serialized hardware must be physically joined. This catches caps, rear
    # covers and bezels separated from their shell by even a tiny air gap.
    joined_paths = [f"block/desk_console_{p[0]}" for p in PLATFORMS]
    joined_paths += ["block/arcade_cabinet_2p", "block/desk_console", "block/handheld_dock",
                     "block/cartridge_writer", "item/template_handheld", "item/controller",
                     "item/template_cartridge"]
    joined_paths += [f"item/cartridge_{p[0]}" for p in PLATFORMS]
    for model_id in joined_paths:
        elements = resolved(f"{ASSETS}/models/{model_id}.json")["elements"]
        joined, pending = {0}, [0]
        while pending:
            current = pending.pop()
            for other in range(len(elements)):
                if other in joined:
                    continue
                if all(min(elements[current]["to"][axis], elements[other]["to"][axis]) >=
                       max(elements[current]["from"][axis], elements[other]["from"][axis]) - 1e-7
                       for axis in range(3)):
                    joined.add(other)
                    pending.append(other)
        if len(joined) != len(elements):
            raise ValueError(f"Hardware has disconnected geometry: {model_id}")
        checks += 1
    # The full live viewport must be free of opaque controls and case panels.
    # Check the actual authored coordinates, not a label describing the layout.
    for entry in [*model_catalog()["entries"], *model_catalog()["additional_styles"]]:
        model_id = entry["geometry"].split(":", 1)[1]
        elements = resolved(f"{ASSETS}/models/{model_id}.json")["elements"]
        planes = entry.get("screen_planes", [entry.get("screen_plane")])
        for plane in planes:
            if not plane:
                continue
            x0, y0, z = plane["from"]
            x1, y1, _ = plane["to"]
            for element in elements:
                if element["from"][2] < z - 1e-6 and \
                        min(element["to"][0], x1) > max(element["from"][0], x0) + 1e-6 and \
                        min(element["to"][1], y1) > max(element["from"][1], y0) + 1e-6:
                    raise ValueError(f"Opaque hardware covers the live viewport: {model_id}")
            checks += 1
    generic = resolved(f"{ASSETS}/models/item/template_handheld.json")["elements"]
    bounds = [min(element["from"][axis] for element in generic) for axis in range(3)] + \
             [max(element["to"][axis] for element in generic) for axis in range(3)]
    if bounds != [0, 3, 5.8, 16, 12.4, 8.5]:
        raise ValueError("Generic-zero handheld must retain its renderer bounds contract")
    checks += 1
    return checks


