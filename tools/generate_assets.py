def check_closure(files):
    """Resolve inherited model textures and all local references, not just JSON syntax."""
    checks = 0

    def require(path):
        nonlocal checks
        checks += 1
        if path not in files:
            raise ValueError(f"Missing resource: {path}")

    def local_model(resource):
        namespace, path = resource.split(":", 1)
        if namespace != NS:
            raise ValueError(f"Unexpected model namespace: {resource}")
        return f"{ASSETS}/models/{path}.json"

    def resolved(path, stack=()):
        require(path)
        if path in stack:
            raise ValueError(f"Cyclic model inheritance: {path}")
        model = json.loads(files[path])
        if "parent" in model:
            inherited = resolved(local_model(model["parent"]), (*stack, path))
            inherited["textures"].update(model.get("textures", {}))
            if "elements" in model:
                inherited["elements"] = model["elements"]
            return inherited
        return copy.deepcopy(model)

    for path, payload in files.items():
        if path.endswith(".json"):
            data = json.loads(payload)
            checks += 1
            if "/models/" in path:
                full = resolved(path)
                textures = full["textures"]
                for texture in textures.values():
                    if texture.startswith("#"):
                        continue
                    namespace, texture_path = texture.split(":", 1)
                    if namespace != NS:
                        raise ValueError(f"Unexpected texture namespace: {texture}")
                    # MC 1.21.1's vanilla blocks atlas has directory sources for
                    # block/ and item/. Existing files outside those sources are
                    # not implicitly stitched just because a model names them.
                    if not texture_path.startswith(("block/", "item/")):
                        raise ValueError(f"Model texture is outside block/item atlas sources: {texture}")
                    require(f"{ASSETS}/textures/{texture_path}.png")
                    checks += 1
                for element in full["elements"]:
                    if not all(0 <= a < b <= 16 for a, b in zip(element["from"], element["to"])):
                        raise ValueError(f"Invalid model element bounds: {path}")
                    for face in element["faces"].values():
                        key = face["texture"]
                        visited = set()
                        while key.startswith("#"):
                            if key in visited or key[1:] not in textures:
                                raise ValueError(f"Unresolved texture {key}: {path}")
                            visited.add(key)
                            key = textures[key[1:]]
                        checks += 1
                for override in data.get("overrides", []):
                    require(local_model(override["model"]))
            if "/blockstates/" in path:
                for variant in data["variants"].values():
                    require(local_model(variant["model"]))
            if "/recipe/" in path:
                output = data["result"]["id"].split(":", 1)[1]
                if output not in ITEMS or output == "cartridge":
                    raise ValueError(f"Invalid crafting output: {output}")
                require(f"{ASSETS}/models/item/{output}.json")
        if path.endswith(".png"):
            checks += 1
            try:
                decode_png(payload)
            except ValueError as error:
                raise ValueError(f"Invalid decoded PNG {path}: {error}") from error
    for name in ITEMS:
        require(f"{ASSETS}/models/item/{name}.json")
    locales = [json.loads(files[f"{ASSETS}/lang/{locale}.json"]) for locale in ("zh_cn", "en_us")]
    if set(locales[0]) != set(locales[1]):
        raise ValueError("Locale key sets differ")
    for platform, *_ in PLATFORMS:
        if f"platform.{NS}.{platform}" not in locales[0]:
            raise ValueError(f"Missing platform translation: {platform}")
        checks += 1
    return checks


