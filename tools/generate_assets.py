def rgba(color: str, alpha: int = 255) -> tuple[int, int, int, int]:
    return tuple(int(color[i:i + 2], 16) for i in (0, 2, 4)) + (alpha,)


def png(width: int, height: int, pixels: list[tuple]) -> bytes:
    def chunk(kind: bytes, payload: bytes) -> bytes:
        return struct.pack(">I", len(payload)) + kind + payload + struct.pack(
            ">I", zlib.crc32(kind + payload) & 0xFFFFFFFF)
    raw = b"".join(b"\x00" + bytes(sum((list(p) for p in pixels[y * width:(y + 1) * width]), []))
                   for y in range(height))
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)) + chunk(
        b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def decode_png(payload: bytes):
    """Independently validate RGBA8 PNG chunks, CRCs, zlib and all row filters."""
    if not payload.startswith(b"\x89PNG\r\n\x1a\n"):
        raise ValueError("Invalid PNG signature")
    position, header, compressed, ended = 8, None, bytearray(), False
    while position < len(payload):
        if position + 12 > len(payload):
            raise ValueError("Truncated PNG chunk")
        length = struct.unpack_from(">I", payload, position)[0]
        kind = payload[position + 4:position + 8]
        end = position + length + 12
        if end > len(payload):
            raise ValueError("Truncated PNG payload")
        body = payload[position + 8:end - 4]
        crc = struct.unpack_from(">I", payload, end - 4)[0]
        if zlib.crc32(kind + body) & 0xffffffff != crc:
            raise ValueError("PNG chunk CRC mismatch")
        if header is None and kind != b"IHDR":
            raise ValueError("PNG header is not first")
        if kind == b"IHDR":
            if header is not None or length != 13:
                raise ValueError("Invalid PNG header")
            header = struct.unpack(">IIBBBBB", body)
            width, height, bits, color, compression, filtering, interlace = header
            if width < 1 or height < 1 or width > 4096 or height > 4096:
                raise ValueError("PNG dimensions exceed authored texture limits")
            if (bits, color, compression, filtering, interlace) != (8, 6, 0, 0, 0):
                raise ValueError("Authored PNG must be noninterlaced RGBA8")
        elif kind == b"IDAT":
            compressed.extend(body)
        elif kind == b"IEND":
            if length or end != len(payload):
                raise ValueError("Invalid PNG end")
            ended = True
            break
        position = end
    if header is None or not ended or not compressed:
        raise ValueError("Incomplete PNG")
    stride = width * 4
    decoder = zlib.decompressobj()
    raw = decoder.decompress(bytes(compressed), height * (stride + 1) + 1)
    if not decoder.eof or decoder.unused_data or decoder.unconsumed_tail or len(raw) != height * (stride + 1):
        raise ValueError("Invalid PNG image stream")
    pixels, previous = bytearray(), bytearray(stride)
    for y in range(height):
        offset = y * (stride + 1)
        filtering = raw[offset]
        row = bytearray(raw[offset + 1:offset + 1 + stride])
        if filtering not in range(5):
            raise ValueError("Invalid PNG row filter")
        for x in range(stride):
            left = row[x - 4] if x >= 4 else 0
            up = previous[x]
            upper_left = previous[x - 4] if x >= 4 else 0
            if filtering == 1:
                value = left
            elif filtering == 2:
                value = up
            elif filtering == 3:
                value = (left + up) // 2
            elif filtering == 4:
                estimate = left + up - upper_left
                distances = (abs(estimate - left), abs(estimate - up), abs(estimate - upper_left))
                value = (left, up, upper_left)[distances.index(min(distances))]
            else:
                value = 0
            row[x] = (row[x] + value) & 255
        pixels.extend(row)
        previous = row
    return width, height, bytes(pixels)


def canvas(width: int, height: int, color: str = "000000", alpha: int = 255):
    return [rgba(color, alpha)] * (width * height)


def rect(pixels, width, x0, y0, x1, y1, color):
    value = rgba(color) if isinstance(color, str) else color
    height = len(pixels) // width
    for y in range(max(0, y0), min(height, y1)):
        for x in range(max(0, x0), min(width, x1)):
            pixels[y * width + x] = value


def text_pixels(pixels, width, x, y, label, color, scale=1):
    for letter in label:
        glyph = GLYPHS[letter]
        for row, line in enumerate(glyph):
            for col, bit in enumerate(line):
                if bit == "1":
                    rect(pixels, width, x + col * scale, y + row * scale,
                         x + (col + 1) * scale, y + (row + 1) * scale, color)
        x += 4 * scale


def surface(color):
    pixels = canvas(16, 16, color)
    rgb = rgba(color)
    light = tuple(min(255, c + 7) for c in rgb[:3]) + (255,)
    shade = tuple(max(0, c - 5) for c in rgb[:3]) + (255,)
    for x, y in ((2, 3), (11, 5), (5, 12)):
        pixels[y * 16 + x] = light
    for x, y in ((7, 6), (13, 13)):
        pixels[y * 16 + x] = shade
    return png(16, 16, pixels)


def label_texture(short: str, color: str, index: int):
    pixels = canvas(32, 32, COLORS["shell"])
    rect(pixels, 32, 0, 0, 32, 4, color)
    rect(pixels, 32, 0, 28, 32, 32, COLORS["ink"])
    label_scale = 2 if len(short) <= 3 else 1
    label_width = (4 * len(short) - 1) * label_scale
    text_pixels(pixels, 32, (32 - label_width) // 2, 8, short, COLORS["ink"], label_scale)
    text_pixels(pixels, 32, 21, 21, f"{index:02d}", COLORS["ink"])
    # A stepped three-petal module mark; authored here, no source image.
    for x, y in ((3, 21), (5, 19), (7, 21), (5, 23)):
        rect(pixels, 32, x, y, x + 2, y + 2, color)
    return png(32, 32, pixels)


def box(start, end, material="shell", **faces):
    return {"from": start, "to": end, "faces": {
        face: {"uv": [0, 0, 16, 16], "texture": "#" + faces.get(face, material)}
        for face in FACES}}


def base_model(elements, textures=None, kind="block"):
    palette = {name: f"{NS}:block/common/{name}" for name in COLORS}
    palette.update({"accent": f"{NS}:block/common/amber", "label": f"{NS}:item/label_blank",
                    "display": f"{NS}:block/standby"})
    palette.update(textures or {})
    display = {
        "gui": {"rotation": [25, 225, 0], "translation": [0, 0, 0], "scale": [0.85] * 3},
        "ground": {"rotation": [0, 0, 0], "translation": [0, 2, 0], "scale": [0.45] * 3},
        "fixed": {"rotation": [0, 180, 0], "translation": [0, 0, 0], "scale": [0.75] * 3},
        "thirdperson_righthand": {"rotation": [65, 45, 0], "translation": [0, 2, 0], "scale": [0.45] * 3},
        "firstperson_righthand": {"rotation": [0, 45, 0], "translation": [0, 1, 0], "scale": [0.55] * 3},
        "thirdperson_lefthand": {"rotation": [65, 225, 0], "translation": [0, 2, 0], "scale": [0.45] * 3},
        "firstperson_lefthand": {"rotation": [0, 225, 0], "translation": [0, 1, 0], "scale": [0.55] * 3},
    }
    if kind == "item":
        display["gui"] = {"rotation": [10, 195, 0], "translation": [0, 0, 0], "scale": [0.9] * 3}
    return {"textures": {"particle": palette["ink"], **palette}, "ambientocclusion": True,
            "elements": elements, "display": display}


