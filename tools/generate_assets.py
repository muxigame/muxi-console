def preview():
    """Original orthographic contact sheet, useful before native Minecraft QA."""
    width, height = 1200, 1100
    pixels = canvas(width, height, "F2EFE5")
    depth = [-math.inf] * (width * height)
    mesh = models()
    authored = generated_files()
    sampled = {}

    def face_color(model, material):
        texture = model["textures"][material]
        while texture.startswith("#"):
            texture = model["textures"][texture[1:]]
        if texture not in sampled:
            _, path = texture.split(":", 1)
            w, h, raw = decode_png(authored[f"{ASSETS}/textures/{path}.png"])
            sampled[texture] = tuple(sum(raw[channel::4]) // (w*h) for channel in range(3))
        return sampled[texture]
    tiles = [f"block/desk_console_{p[0]}" for p in PLATFORMS] + ["block/arcade_cabinet_2p"]
    # Top and north faces visible, like a camera above the front-right corner.
    def project(x, y, z, cx, cy):
        return (cx - (x - 8) * 8 - (z - 8) * 4,
                cy - (y - 7) * 8 - (z - 8) * 4.8 + (x - 8) * 2.4,
                x + y * 1.5 - z * 2)

    def triangle(vertices, color):
        a, b, c = vertices
        low_x, high_x = max(0, int(min(v[0] for v in vertices))), min(width - 1, math.ceil(max(v[0] for v in vertices)))
        low_y, high_y = max(0, int(min(v[1] for v in vertices))), min(height - 1, math.ceil(max(v[1] for v in vertices)))
        divisor = (b[1] - c[1]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[1] - c[1])
        if not divisor:
            return
        for y in range(low_y, high_y + 1):
            for x in range(low_x, high_x + 1):
                u = ((b[1] - c[1]) * (x - c[0]) + (c[0] - b[0]) * (y - c[1])) / divisor
                v = ((c[1] - a[1]) * (x - c[0]) + (a[0] - c[0]) * (y - c[1])) / divisor
                w = 1 - u - v
                if min(u, v, w) >= -1e-5:
                    d = u * a[2] + v * b[2] + w * c[2]
                    index = y * width + x
                    if d > depth[index]:
                        depth[index] = d
                        pixels[index] = color
    for index, name in enumerate(tiles):
        cx, cy = 120 + index % 5 * 240, 110 + index // 5 * 220
        rect(pixels, width, cx - 112, cy - 102, cx + 112, cy + 102, "E6E4D9")
        text_pixels(pixels, width, cx - 104, cy - 94, f"{index + 1:02d}", COLORS["ink"], 2)
        for element in mesh[name]["elements"]:
            x0, y0, z0 = element["from"]
            x1, y1, z1 = element["to"]
            face_vertices = {
                "up": [(x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)],
                "north": [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0)],
                "east": [(x1, y0, z0), (x1, y0, z1), (x1, y1, z1), (x1, y1, z0)],
            }
            for face, vertices in face_vertices.items():
                material = element["faces"][face]["texture"][1:]
                shade = {"up": 1.1, "north": 0.95, "east": 0.72}[face]
                rgb = tuple(min(255, int(v * shade)) for v in face_color(mesh[name],material)) + (255,)
                pts = [project(*vertex, cx, cy) for vertex in vertices]
                triangle(pts[:3], rgb)
                triangle([pts[0], pts[2], pts[3]], rgb)
    out = ROOT / "build/assets-preview.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(png(width, height, pixels))
    return out


def review_plan():
    """A layout for the root runner; this function never launches Minecraft."""
    catalog = model_catalog()
